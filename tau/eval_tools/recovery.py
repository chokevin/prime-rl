"""Narrow, explicit cross-generation contract for the one F12 post-eval recovery.

The F12 post-training evaluation (frozen source generation
``a603e791776a4579440edc5df5b70309c61cf46a``) published complete, immutable reward and
comparison evidence, but its final ``inference.log`` promotion was interrupted. This
module pins the exact immutable F12 inputs so a fresh post-eval replay can run in a NEW
runtime-source generation — reading those frozen inputs read-only, writing only into its
own ``eval-post-recovery`` leaf, and never touching the F12 generation (including its
preserved partial ``eval-post/inference.log``).

Every value the recovery Tau target supplies is checked against these source-owned
constants; there is deliberately no arbitrary-source escape hatch. The recovery keeps the
model, decoding, grader, seed, all-500 example ordering, baseline, adapter, comparison
algorithm, bootstrap seed/count, and unchanged gate (delta >= +0.03 AND CI lower > 0)
byte-for-byte identical to the frozen F12 post eval; there are no alternate
checkpoint/reroll knobs.

Terminal-state rule: once immutable post rewards, the comparison, and the provenance
record are durable, an isolated failure of the final ``inference.log`` promotion alone is
never a reason to resubmit. The comparison remains the experiment result and the attempt
log is the diagnostic artifact.
"""

from __future__ import annotations

import os
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path

from tau.eval_tools.artifacts import ADAPTER_CONFIG, ADAPTER_WEIGHT_FILES, TrainingResult
from tau.eval_tools.compare import ComparisonResult, RewardRecord
from tau.eval_tools.json_io import load_json_with_sha256, write_json_exclusive
from tau.eval_tools.manifest import GIT_SHA_RE, SHA256_RE, FrozenEvalManifest
from tau.eval_tools.output_paths import (
    RECOVERY_OUTPUT_LEAF,
    RECOVERY_SOURCE_REVISION,
    EvidenceGeneration,
    evidence_generation,
)

#: Provenance/contract schema version for the recovery artifact this module writes.
RECOVERY_CONTRACT_VERSION = 1

#: The immutable F12 input contract, generated by F12 source generation
#: a603e791776a4579440edc5df5b70309c61cf46a. Each value is checked against the exact
#: file bytes / internal identity of the input the recovery Tau target supplies.
F12_MANIFEST_FILE_SHA256 = "759bb7ba018f75d3c3dee219e0746e00d2ff0c7531ddc986becac4f909291845"
F12_MANIFEST_IDENTITY_HASH = "2a35089008d5f5b2e0606facafe88b5534c155d1fd95787482aaef4f9cdba673"
F12_BASELINE_REWARDS_FILE_SHA256 = "8fc09bce4b4ecaf5256712d2b0eb1b72979e8f5a250f86e1e8e310ec3b2ec000"
F12_BASELINE_MEAN = 0.738
F12_EXAMPLE_COUNT = 500
F12_TRAINING_RESULT_FILE_SHA256 = "72b197a353978cff2a8c51aad6e8a45157bef189bac449a00384b3755744a0f3"
F12_TRAINING_STATUS = "success"
F12_TRAINING_SOURCE_STEP = 200
F12_TRAINING_ATTEMPT_ID = "20260804T013900Z-0de01384c398f8d3"
F12_FINAL_ADAPTER_AGGREGATE_SHA256 = "48e6e1fe8dd4039e9fb716cff91101bc463f8198ef499c040e81b90b72af6f9e"
F12_ADAPTER_CONFIG_SHA256 = "f1dcd0c6293492cf407eb63d8c8198360f8859433ad08ca1899dbffd7a8f50b5"
F12_ADAPTER_MODEL_SHA256 = "6bea386c91b51916bef28aa9e841e4a48cdc81ac0ce2c39bbb92239789eb0801"
F12_MODEL_FILES_AGGREGATE_SHA256 = "d2d9ab0fbeed7ab74ff3dc433209aec9b01952ccc4d88eec16c0d9aaf1fef9c8"
F12_TRAINING_DATA_DIGEST = "d5924980fe96e2a5ae2de7cd9470c061432adc15f5ac488535cd0f6ac0e8a155"
F12_SOURCE_CONFIG_SHA256 = "5450d2ff141172a4ababc5dfe3df572f2764cba5c6e998d982bb21d270e9e2ff"
F12_MAX_STEPS = 200
F12_MONITORING_INTERVAL = 100
F12_LORA_RANK = 16
F12_ADAPTER_WEIGHT_NAME = ADAPTER_WEIGHT_FILES[0]


class RecoveryContractError(ValueError):
    """Raised when a supplied F12 input does not match the pinned immutable contract."""


@dataclass(frozen=True)
class RecoveryContract:
    """The verified frozen-F12 identities the recovery run binds into its provenance."""

    frozen_source_revision: str
    manifest_path: Path
    baseline_rewards_path: Path
    training_result_path: Path
    training_output_dir: Path
    lora_adapter_path: Path
    manifest_identity_hash: str
    evaluation_identity_hash: str
    baseline_rewards_sha256: str
    training_result_sha256: str
    adapter_aggregate_sha256: str
    training_attempt_id: str
    source_step: int


def _require(condition: bool, message: str) -> None:
    if not condition:
        raise RecoveryContractError(message)


def _frozen_generation(data_root: Path) -> EvidenceGeneration:
    return evidence_generation(RECOVERY_SOURCE_REVISION, data_root=data_root)


def _canonical(path: str | Path) -> Path:
    return Path(os.path.abspath(path))


def validate_recovery_contract(
    *,
    manifest_path: str | Path,
    baseline_rewards_path: str | Path,
    training_result_path: str | Path,
    training_output_dir: str | Path,
    lora_adapter_path: str | Path,
    data_root: Path = Path("/data"),
) -> RecoveryContract:
    """Validate every recovery input against the pinned F12 immutable contract.

    Checks: exact canonical paths in the frozen generation, the frozen source SHA, full
    manifest/baseline/training-result file digests, internal manifest and training-result
    identities, source step, adapter aggregate and per-file digests, and the 500 baseline
    example ids/mean. Raises on any mismatch; there are no semantic changes to the frozen
    experiment.
    """
    frozen = _frozen_generation(data_root)

    manifest_path = _canonical(manifest_path)
    baseline_rewards_path = _canonical(baseline_rewards_path)
    training_result_path = _canonical(training_result_path)
    training_output_dir = _canonical(training_output_dir)
    lora_adapter_path = _canonical(lora_adapter_path)

    _require(manifest_path == frozen.frozen_manifest, f"manifest path {manifest_path} is not the frozen F12 manifest")
    _require(
        baseline_rewards_path == frozen.baseline_rewards,
        f"baseline rewards path {baseline_rewards_path} is not the frozen F12 baseline",
    )
    _require(
        training_result_path == frozen.training_result,
        f"training result path {training_result_path} is not the frozen F12 training result",
    )
    _require(
        training_output_dir == frozen.train,
        f"training output dir {training_output_dir} is not the frozen F12 train generation",
    )
    _require(
        lora_adapter_path == frozen.final_adapter,
        f"adapter path {lora_adapter_path} is not the frozen F12 final adapter",
    )

    # --- Frozen manifest: file bytes + internal finalized identity ---------------------
    manifest_payload, manifest_sha = load_json_with_sha256(manifest_path)
    _require(
        manifest_sha == F12_MANIFEST_FILE_SHA256,
        f"frozen manifest SHA-256 {manifest_sha} does not match pinned {F12_MANIFEST_FILE_SHA256}",
    )
    manifest = FrozenEvalManifest.model_validate(manifest_payload)
    _require(manifest.state == "finalized", "frozen manifest must be finalized")
    _require(
        manifest.source_revision == RECOVERY_SOURCE_REVISION,
        f"frozen manifest source revision {manifest.source_revision} is not the pinned F12 source",
    )
    manifest_identity = manifest.identity_hash()
    _require(
        manifest_identity == F12_MANIFEST_IDENTITY_HASH,
        f"frozen manifest identity {manifest_identity} does not match pinned {F12_MANIFEST_IDENTITY_HASH}",
    )
    _require(
        manifest.baseline_mean == F12_BASELINE_MEAN,
        f"frozen manifest baseline mean {manifest.baseline_mean} does not match pinned {F12_BASELINE_MEAN}",
    )
    example_ids = manifest.example_ids
    _require(
        len(example_ids) == F12_EXAMPLE_COUNT,
        f"frozen manifest covers {len(example_ids)} examples, expected {F12_EXAMPLE_COUNT}",
    )
    _require(
        manifest.baseline_rewards_sha256 == F12_BASELINE_REWARDS_FILE_SHA256,
        "frozen manifest baseline rewards digest does not match the pinned baseline artifact",
    )
    evaluation_identity = manifest.evaluation_identity_hash()

    # --- Frozen baseline rewards: file bytes + example set + mean ----------------------
    baseline_payload, baseline_sha = load_json_with_sha256(baseline_rewards_path)
    _require(
        baseline_sha == F12_BASELINE_REWARDS_FILE_SHA256,
        f"frozen baseline rewards SHA-256 {baseline_sha} does not match pinned {F12_BASELINE_REWARDS_FILE_SHA256}",
    )
    baseline = RewardRecord.model_validate(baseline_payload)
    _require(baseline.model_label == "baseline", "frozen baseline artifact is not labeled baseline")
    _require(
        baseline.evaluation_identity_hash == evaluation_identity,
        "frozen baseline artifact evaluation identity does not match the frozen manifest",
    )
    _require(
        baseline.frozen_manifest_identity_hash is None,
        "frozen baseline artifact must predate finalization and omit a frozen manifest identity",
    )
    _require(
        len(baseline.rewards) == F12_EXAMPLE_COUNT,
        f"frozen baseline artifact has {len(baseline.rewards)} rows, expected {F12_EXAMPLE_COUNT}",
    )
    _require(
        {int(example_id) for example_id in baseline.rewards} == example_ids,
        "frozen baseline artifact example ids do not match the frozen manifest exactly",
    )
    baseline_mean = sum(baseline.rewards.values()) / len(baseline.rewards)
    _require(
        baseline_mean == F12_BASELINE_MEAN,
        f"frozen baseline artifact mean {baseline_mean} does not match pinned {F12_BASELINE_MEAN}",
    )

    # --- Frozen training result: file bytes + internal identities + adapter ------------
    result_payload, result_sha = load_json_with_sha256(training_result_path)
    _require(
        result_sha == F12_TRAINING_RESULT_FILE_SHA256,
        f"frozen training result SHA-256 {result_sha} does not match pinned {F12_TRAINING_RESULT_FILE_SHA256}",
    )
    result = TrainingResult.model_validate(result_payload)
    _require(
        result.status == F12_TRAINING_STATUS, f"frozen training result status is {result.status!r}, expected success"
    )
    _require(
        result.attempt_id == F12_TRAINING_ATTEMPT_ID,
        f"frozen training result attempt id {result.attempt_id} does not match pinned {F12_TRAINING_ATTEMPT_ID}",
    )
    _require(
        result.source_step == F12_TRAINING_SOURCE_STEP,
        f"frozen training result source step {result.source_step} does not match pinned {F12_TRAINING_SOURCE_STEP}",
    )
    _require(
        result.source_revision == RECOVERY_SOURCE_REVISION,
        "frozen training result source revision does not match the pinned F12 source",
    )
    _require(
        result.manifest_identity_hash == F12_MANIFEST_IDENTITY_HASH,
        "frozen training result manifest identity does not match the pinned F12 manifest identity",
    )
    _require(
        result.model_files_sha256 == F12_MODEL_FILES_AGGREGATE_SHA256,
        "frozen training result base-model aggregate does not match pinned model files digest",
    )
    _require(
        result.training_data_digest == F12_TRAINING_DATA_DIGEST,
        "frozen training result training-data digest does not match pinned digest",
    )
    _require(
        result.rl_config.max_steps == F12_MAX_STEPS,
        f"frozen training result max_steps {result.rl_config.max_steps} does not match pinned {F12_MAX_STEPS}",
    )
    _require(
        result.rl_config.source_toml_sha256 == F12_SOURCE_CONFIG_SHA256,
        "frozen training result source config digest does not match pinned source config digest",
    )
    _require(
        result.lora_rank == F12_LORA_RANK,
        f"frozen training result LoRA rank is {result.lora_rank}, expected {F12_LORA_RANK}",
    )
    _require(
        result.adapter_sha256 == F12_FINAL_ADAPTER_AGGREGATE_SHA256,
        "frozen training result adapter aggregate does not match pinned final adapter aggregate",
    )
    adapter_digests = {record.path: record.sha256 for record in result.adapter_files.files}
    _require(
        adapter_digests.get(ADAPTER_CONFIG) == F12_ADAPTER_CONFIG_SHA256,
        "frozen adapter config digest does not match pinned adapter_config.json digest",
    )
    _require(
        adapter_digests.get(F12_ADAPTER_WEIGHT_NAME) == F12_ADAPTER_MODEL_SHA256,
        "frozen adapter weight digest does not match pinned adapter_model.safetensors digest",
    )

    return RecoveryContract(
        frozen_source_revision=RECOVERY_SOURCE_REVISION,
        manifest_path=manifest_path,
        baseline_rewards_path=baseline_rewards_path,
        training_result_path=training_result_path,
        training_output_dir=training_output_dir,
        lora_adapter_path=lora_adapter_path,
        manifest_identity_hash=manifest_identity,
        evaluation_identity_hash=evaluation_identity,
        baseline_rewards_sha256=baseline_sha,
        training_result_sha256=result_sha,
        adapter_aggregate_sha256=result.adapter_sha256,
        training_attempt_id=result.attempt_id,
        source_step=result.source_step,
    )


def _validate_runtime_source_revision(runtime_source_revision: str) -> str:
    if not GIT_SHA_RE.fullmatch(runtime_source_revision):
        raise RecoveryContractError("runtime source revision must be a full 40-character lowercase commit SHA")
    if runtime_source_revision == RECOVERY_SOURCE_REVISION:
        raise RecoveryContractError("recovery runtime source must be distinct from the frozen F12 source generation")
    return runtime_source_revision


def write_recovery_provenance(
    *,
    output_dir: str | Path,
    runtime_source_revision: str,
    comparison_path: str | Path,
    contract: RecoveryContract,
    data_root: Path = Path("/data"),
) -> Path:
    """Write ``recovery-provenance.json`` binding both the recovery runtime source and the
    frozen F12 experiment source to the durable comparison result.

    Written after the comparison is durable and before final log promotion, so the result
    provenance is complete even if the isolated log promotion later fails.
    """
    _validate_runtime_source_revision(runtime_source_revision)
    runtime_generation = evidence_generation(runtime_source_revision, data_root=data_root)
    expected_output = runtime_generation.root / RECOVERY_OUTPUT_LEAF
    output_dir = _canonical(output_dir)
    if output_dir != expected_output:
        raise RecoveryContractError(
            f"recovery output dir {output_dir} is not the runtime-source recovery leaf {expected_output}"
        )

    comparison_path = _canonical(comparison_path)
    if comparison_path.parent != output_dir:
        raise RecoveryContractError(
            f"comparison path {comparison_path} is not directly under the recovery output dir {output_dir}"
        )

    comparison_payload, comparison_sha = load_json_with_sha256(comparison_path)
    comparison = ComparisonResult.model_validate(comparison_payload)
    if comparison.manifest_identity_hash != contract.manifest_identity_hash:
        raise RecoveryContractError("comparison manifest identity does not match the verified frozen manifest identity")
    if comparison.baseline_rewards_sha256 != contract.baseline_rewards_sha256:
        raise RecoveryContractError("comparison baseline digest does not match the verified frozen baseline digest")
    if not SHA256_RE.fullmatch(comparison.post_rewards_sha256):
        raise RecoveryContractError("comparison post rewards digest is malformed")

    provenance = {
        "recovery_contract_version": RECOVERY_CONTRACT_VERSION,
        "created_at": datetime.now(timezone.utc).isoformat(),
        "runtime_source_revision": runtime_source_revision,
        "frozen_f12_source_revision": contract.frozen_source_revision,
        "recovery_output_leaf": RECOVERY_OUTPUT_LEAF,
        "frozen_inputs": {
            "manifest_path": str(contract.manifest_path),
            "manifest_sha256": F12_MANIFEST_FILE_SHA256,
            "manifest_identity_hash": contract.manifest_identity_hash,
            "evaluation_identity_hash": contract.evaluation_identity_hash,
            "baseline_rewards_path": str(contract.baseline_rewards_path),
            "baseline_rewards_sha256": contract.baseline_rewards_sha256,
            "baseline_mean": F12_BASELINE_MEAN,
            "example_count": F12_EXAMPLE_COUNT,
            "training_result_path": str(contract.training_result_path),
            "training_result_sha256": contract.training_result_sha256,
            "training_attempt_id": contract.training_attempt_id,
            "source_step": contract.source_step,
            "adapter_path": str(contract.lora_adapter_path),
            "adapter_aggregate_sha256": contract.adapter_aggregate_sha256,
            "adapter_config_sha256": F12_ADAPTER_CONFIG_SHA256,
            "adapter_model_sha256": F12_ADAPTER_MODEL_SHA256,
            "model_files_aggregate_sha256": F12_MODEL_FILES_AGGREGATE_SHA256,
            "training_data_digest": F12_TRAINING_DATA_DIGEST,
            "source_config_sha256": F12_SOURCE_CONFIG_SHA256,
            "max_steps": F12_MAX_STEPS,
            "monitoring_interval": F12_MONITORING_INTERVAL,
            "lora_rank": F12_LORA_RANK,
        },
        "comparison": {
            "path": str(comparison_path),
            "sha256": comparison_sha,
            "passed": comparison.passed,
            "n": comparison.n,
            "baseline_mean": comparison.baseline_mean,
            "post_mean": comparison.post_mean,
            "delta": comparison.delta,
            "ci_lower": comparison.ci_lower,
            "ci_upper": comparison.ci_upper,
            "n_bootstrap": comparison.n_bootstrap,
            "bootstrap_seed": comparison.bootstrap_seed,
            "manifest_identity_hash": comparison.manifest_identity_hash,
            "baseline_rewards_sha256": comparison.baseline_rewards_sha256,
            "post_rewards_sha256": comparison.post_rewards_sha256,
        },
    }
    provenance_path = output_dir / "recovery-provenance.json"
    write_json_exclusive(provenance_path, provenance)
    return provenance_path
